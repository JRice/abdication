"""Embed the ABDrum sample library in the plugin.

    python tools/gen-samplelib.py ["<path to abdrum library>"]

Reads every .wav in the library's noise folders (steady, crackle,
modulated) and transient folders (thump, knock, spark), each in
alphabetical order as the library README promises, and writes:

  plugin/src/samplelib.bin        all samples, 16-bit little-endian, back to back
                                  (loops first, then hits; half the size of float)
  plugin/src/samplelib_index.rs   where each one starts and how long it is
  plugin/src/samplelib.json       the same index, for the offline renderer
  dsp/samplelib.lib               the Loop menu, the hit sets, and the readers

Faust reads through two external functions (plugin/src/samplelib.rs):
sl_loop(index, position) wraps the position, so a loop repeats seamlessly;
sl_hit(index, position) is silent outside the hit.
Run from the repo root after changing the library; then gen-rust.sh and rebuild."""
import json
import os
import sys

import numpy as np
import scipy.io.wavfile as wavfile

LIBRARY = sys.argv[1] if len(sys.argv) > 1 else os.path.join("..", "abdrum library")
LOOP_GROUPS = ["steady", "crackle", "modulated"]       # Loop menu order
HIT_SETS = ["thump", "knock", "spark"]                 # Set menu order
RATE = 44100


def read_mono(path):
    rate, data = wavfile.read(path)
    assert rate == RATE, f"{path}: {rate} Hz, expected {RATE} (run build_library.py conform)"
    scale = {np.dtype("int16"): 2**15, np.dtype("int32"): 2**31}.get(data.dtype, 1)
    data = data.astype(np.float64) / scale
    if data.ndim > 1:
        data = data.mean(axis=1)
    return data.astype("<f4")


def label(group, filename):
    name = os.path.splitext(filename)[0].replace("'", "").replace(";", ",")
    return f"{group.capitalize()}: {name}"


def collect(family, groups):
    clips, labels, counts = [], [], []
    for group in groups:
        folder = os.path.join(LIBRARY, family, group)
        names = sorted(f for f in os.listdir(folder) if f.lower().endswith(".wav"))
        clips += [read_mono(os.path.join(folder, fn)) for fn in names]
        labels += [label(group, fn) for fn in names]
        counts.append(len(names))
    return clips, labels, counts


loops, loop_labels, _ = collect("noise", LOOP_GROUPS)
hits, hit_labels, set_counts = collect("transients", HIT_SETS)
clips = loops + hits
starts = [int(s) for s in np.cumsum([0] + [len(c) for c in clips[:-1]])]
lens = [len(c) for c in clips]
loop_starts, hit_starts = starts[:len(loops)], starts[len(loops):]
loop_lens, hit_lens = lens[:len(loops)], lens[len(loops):]
set_first = [int(s) for s in np.cumsum([0] + set_counts[:-1])]
# Body Send gains: equal energy per hit (clamped), so a full send strikes the
# Body about equally hard whichever hit is chosen; its spectrum still decides
# which overtones ring.
energy = np.array([float((h.astype(np.float64) ** 2).sum()) for h in hits])
send_gains = np.clip(np.sqrt(np.median(energy) / np.maximum(energy, 1e-12)), 0.25, 8.0)

pcm = np.round(np.clip(np.concatenate(clips), -1, 1) * 32767).astype("<i2")
pcm.tofile("plugin/src/samplelib.bin")
json.dump({"rate": RATE, "starts": loop_starts, "lens": loop_lens, "labels": loop_labels,
           "hit_starts": hit_starts, "hit_lens": hit_lens, "hit_labels": hit_labels,
           "sets": HIT_SETS, "set_first": set_first, "set_counts": set_counts},
          open("plugin/src/samplelib.json", "w"), indent=1)
with open("plugin/src/samplelib_index.rs", "w") as f:
    f.write("// GENERATED by tools/gen-samplelib.py - do not edit.\n")
    f.write(f"pub const RATE: f32 = {RATE}.0;\n")
    f.write(f"pub const LOOP_STARTS: [u32; {len(loops)}] = {loop_starts};\n")
    f.write(f"pub const LOOP_LENS: [u32; {len(loops)}] = {loop_lens};\n")
    f.write(f"pub const HIT_STARTS: [u32; {len(hits)}] = {hit_starts};\n")
    f.write(f"pub const HIT_LENS: [u32; {len(hits)}] = {hit_lens};\n")
    f.write(f"/// Hit names, in index order ({', '.join(HIT_SETS)}), for a future panel.\n")
    f.write(f"pub const HIT_NAMES: [&str; {len(hits)}] = {json.dumps(hit_labels)};\n")

loop_menu = ";".join(f"'{name}':{i}" for i, name in enumerate(loop_labels))
set_menu = ";".join(f"'{name.capitalize()}':{i}" for i, name in enumerate(HIT_SETS))
pick = lambda values: " + ".join(f"(s == {i}) * {v}" for i, v in enumerate(values))
with open("dsp/samplelib.lib", "w") as f:
    f.write(f"""// GENERATED by tools/gen-samplelib.py - do not edit.
// {len(loops)} noise loops ({", ".join(LOOP_GROUPS)}); {len(hits)} hits ({", ".join(f"{n} {c}" for n, c in zip(HIT_SETS, set_counts))}).

sampleRate = {RATE};

// Loop k at position pos (in samples, wrapped, so it repeats), and hit k at
// pos (silent outside it), served by the plugin (plugin/src/samplelib.rs).
readLoop(k, pos) = ffunction(float sl_loop(int, float), "", "")(int(k), pos);
readHit(k, pos) = ffunction(float sl_hit(int, float), "", "")(int(k), pos);

loopMenu = nentry("[2]Loop [style:menu{{{loop_menu}}}]", 0, 0, {len(loops) - 1}, 1);
setMenu = nentry("[1]Set [style:menu{{{set_menu}}}]", 0, 0, {len(HIT_SETS) - 1}, 1);

// Each set's first hit and size; Sample numbers wrap within the set.
largestSet = {max(set_counts)};
setFirst(s) = {pick(set_first)};
setCount(s) = {pick(set_counts)};
hitIndex(s, n) = setFirst(s) + (int(n) - 1) % int(setCount(s));

// Per-hit Body Send gain: equal energy per hit (clamped to 0.25..8).
hitSendGain(k) = waveform{{{", ".join(f"{g:.4f}" for g in send_gains)}}}, int(k) : rdtable;
""")
print(f"{len(loops)} loops + {len(hits)} hits ({dict(zip(HIT_SETS, set_counts))}), {sum(lens) * 2 / 1e6:.1f} MB")
