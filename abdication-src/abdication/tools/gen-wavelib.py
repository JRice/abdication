"""Build the wave library: every wave set in tables/ as one table, with
band-limited copies per octave so high notes don't alias.

Writes:
  plugin/src/wavelib.bin  the samples (float32 little-endian), embedded by
                          the plugin; Faust reads them through the external
                          function wt_sample(index) (see plugin/src/lib.rs).
  dsp/wavelib.lib         layout constants, the reader, and named menus.
  plugin/src/wavelib_layout.rs  the same layout for the Rust side, which
                          also serves band-limited reads of the basic
                          shapes (wt_basic, used by the Dual oscillator).

Layout: wave w, level L starts at w * WAVE_STRIDE + LEVEL_OFFSET[L] and
is LEVEL_SIZE[L] samples long. Level L keeps harmonics up to
LEVEL_HARMONICS[L] (256 at level 0, halving each level), stored at 4x
oversampling (min 64) so linear interpolation stays clean.

Also writes the wave names for the plugin's menus ("A8 001", "M8 01",
"M16 01" ...).  Run from the repo root after changing tables/."""
import sys
sys.path.insert(0, "tools")
import numpy as np
from wavetools import read_wavetable

SETS = [("argon8-c2", "A8"), ("bitmask-8", "M8"), ("bitmask-16", "M16")]
FRAME = 2048


def basic_waves():
    """Sine, triangle, saw, square, each starting at 0 and rising (like a
    sine), so phase resets and pinches join without a jump where possible.
    Appended after the recorded sets: the Dual oscillator reads them, and
    they're in the Wavetable menus too."""
    x = np.arange(FRAME) / FRAME
    return [("Sine", np.sin(2 * np.pi * x)),
            ("Triangle", 1 - 4 * np.abs((x + 0.25) % 1 - 0.5)),
            ("Saw", 2 * ((x + 0.5) % 1) - 1),
            ("Square", np.where(x < 0.5, 1.0, -1.0))]
HARMONICS = [256 >> L for L in range(8)]            # 256 .. 2
SIZES = [max(64, 4 * h) for h in HARMONICS]
OFFSETS = list(np.cumsum([0] + SIZES[:-1]))
STRIDE = sum(SIZES)


def levels(wave):
    F = np.fft.rfft(wave)
    out = []
    for h, size in zip(HARMONICS, SIZES):
        G = np.zeros(size // 2 + 1, complex)
        G[1:h + 1] = F[1:h + 1] * (size / len(wave))
        out.append(np.fft.irfft(G, size))
    return out


waves, names = [], []
for set_name, prefix in SETS:
    frames = read_wavetable(f"tables/{set_name}.wav")
    width = len(str(len(frames)))
    for i, w in enumerate(frames):
        waves.append(w)
        names.append(f"{prefix} {i + 1:0{width}d}")

basic_base = len(waves)
for name, w in basic_waves():
    waves.append(w)
    names.append(name)

data = np.concatenate([np.concatenate(levels(w)) for w in waves]).astype("<f4")
data.tofile("plugin/src/wavelib.bin")
menu = ";".join(f"'{n}':{i}" for i, n in enumerate(names))
count = len(waves)

with open("plugin/src/wavelib_layout.rs", "w") as f:
    f.write(f"""// GENERATED by tools/gen-wavelib.py - do not edit.
pub const WAVE_STRIDE: usize = {STRIDE};
pub const LEVEL_SIZES: [usize; {len(SIZES)}] = {list(map(int, SIZES))};
pub const LEVEL_OFFSETS: [usize; {len(SIZES)}] = {list(map(int, OFFSETS))};
pub const LEVEL_HARMONICS: [usize; {len(SIZES)}] = {list(map(int, HARMONICS))};
pub const BASIC_BASE: usize = {basic_base};
""")

with open("dsp/wavelib.lib", "w") as f:
    f.write(f"""// GENERATED by tools/gen-wavelib.py from tables/ - do not edit.
// {count} waves; sets: {", ".join(f"{p} = {s}" for s, p in SETS)}.

import("stdfaust.lib");

waveCount     = {count};
waveStride    = {STRIDE};
levelCount    = {len(SIZES)};
levelSize(L)  = ba.selectn({len(SIZES)}, L, {", ".join(map(str, SIZES))});
levelOffset(L)= ba.selectn({len(SIZES)}, L, {", ".join(map(str, OFFSETS))});
levelHarmonics(L) = ba.selectn({len(SIZES)}, L, {", ".join(map(str, HARMONICS))});

// The basic shapes (Sine, Triangle, Saw, Square) start here.
basicBase     = {basic_base};

// Basic shape s (0 sine .. 3 square) at phase q, band-limited for a cycle
// playing at hz; level choice and interpolation happen in the plugin
// (plugin/src/wavelib.rs), which keeps the Faust graph small.
basic(s, hz, q) = ffunction(float wt_basic(int, float, float, float), "", "")(int(s), hz, ma.SR, q);

// Sample i of the whole library, served by the plugin (plugin/src/lib.rs).
tableSize = {len(data)};
table(i)  = ffunction(float wt_sample(int), "", "")(int(i));

// Wave pickers, labelled with wave names (the UI label can't be passed in).
startWave(group) = group(nentry("[1]Start [style:menu{{{menu}}}]", 0, 0, {count - 1}, 1));
midWave(group)   = group(nentry("[2]Mid [style:menu{{{menu}}}]", {min(40, count - 1)}, 0, {count - 1}, 1));
endWave(group)   = group(nentry("[3]End [style:menu{{{menu}}}]", {min(80, count - 1)}, 0, {count - 1}, 1));
// The free LFO's shape: any library wave (Sine by default).
lfoWave(group)   = group(nentry("[2]Shape [style:menu{{{menu}}}]", {basic_base}, 0, {count - 1}, 1));
""")
print(f"{count} waves, {len(data)} samples, stride {STRIDE}")
