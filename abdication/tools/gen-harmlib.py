"""Build the Harmonic EQ's shapes from DS Thorn's Harmonic Filter presets.

    python tools/gen-harmlib.py "C:\\Users\\JRice\\Documents\\DS Audio\\DS Thorn\\Harmonic Filter Presets"

Each .thorn preset is zlib-compressed XML whose first <block> holds, in
JUCE's MemoryBlock base64, 8192 float magnitudes (0..1) then 8192 phases. The
magnitudes are a curve over harmonic number: Thorn reads entry h * k for
harmonic h, its sweep changing k (checked against a bounce of a saw swept
through "Amp 01", which it fits within 5.5 dB RMS over 80 harmonics). The
phases aren't used.

Writes:
  plugin/src/harmlib.bin       every preset's magnitudes as u16 (65535 = 1),
                               8192 per preset, in menu order
  plugin/src/harmlib_index.rs  their names
  dsp/harmlib.lib              the Shape menu (Off, then the presets)

The shapes are DS Audio's, from Jeremy's own install: for his own use."""
import os
import re
import struct
import sys
import zlib

SIZE = 8192
ALPHABET = ".ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+"
LOOKUP = {c: i for i, c in enumerate(ALPHABET)}

src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    r"~\Documents\DS Audio\DS Thorn\Harmonic Filter Presets")
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def juce_base64(text):
    """JUCE's MemoryBlock::fromBase64Encoding: "<size>.<chars>", six bits a
    character, least significant bit first."""
    size, chars = text.split(".", 1)
    out = bytearray(int(size))
    bit = 0
    for ch in chars:
        value = LOOKUP[ch]
        for b in range(6):
            if bit >= len(out) * 8:
                break
            if value >> b & 1:
                out[bit >> 3] |= 1 << (bit & 7)
            bit += 1
    return bytes(out)


names, blob = [], bytearray()
for f in sorted(os.listdir(src), key=str.lower):
    if not f.endswith(".thorn"):
        continue
    xml = zlib.decompress(open(os.path.join(src, f), "rb").read())
    xml = xml[xml.index(b"<plugin"):].decode("latin1")
    block = re.search(r'<block id="[0-9a-f]+" size="65536" data="([^"]+)"', xml).group(1)
    mags = struct.unpack(f"<{SIZE}f", juce_base64(block)[:SIZE * 4])
    names.append(f[:-len(".thorn")])
    blob += struct.pack(f"<{SIZE}H", *(round(min(max(m, 0.0), 1.0) * 65535) for m in mags))
    assert "'" not in names[-1] and '"' not in names[-1]

out = os.path.join(root, "plugin", "src")
with open(os.path.join(out, "harmlib.bin"), "wb") as f:
    f.write(blob)
with open(os.path.join(out, "harmlib_index.rs"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/gen-harmlib.py - do not edit.\n")
    f.write(f"pub const SIZE: usize = {SIZE};\n")
    f.write(f"pub static NAMES: [&str; {len(names)}] = [\n")
    f.writelines(f'    "{n}",\n' for n in names)
    f.write("];\n")
menu = ";".join(["'Off':0"] + [f"'{n}':{i + 1}" for i, n in enumerate(names)])
with open(os.path.join(root, "dsp", "harmlib.lib"), "w", encoding="utf-8") as f:
    f.write(f"""// GENERATED by tools/gen-harmlib.py - do not edit.
// The Harmonic EQ's shapes (DS Thorn's Harmonic Filter presets): Off, then
// shape k is plugin/src/harmlib_index.rs's NAMES[k - 1].

shape(G) = G(nentry("[0]Shape [style:menu{{{menu}}}]", 0, 0, {len(names)}, 1));
""")
print(f"{len(names)} shapes, {len(blob) / 1e6:.2f} MB")
