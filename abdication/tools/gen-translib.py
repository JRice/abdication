"""Build the transient sample library from tables/transients/<set>/.

Writes:
  plugin/src/translib.bin       all samples (float32 little-endian, 44.1 kHz),
                                back to back, embedded by the plugin
  plugin/src/translib_index.rs  where each sample starts and how long it is
  dsp/translib.lib              the Transient "Type" menu: the synthesized
                                types first (their indices never move), then
                                one entry per sample ("Jade 01", "Mech 01" ...)

Faust reads samples through the external function tr_read(sample, position)
(plugin/src/translib.rs). Run from the repo root after changing the sets."""
import json
import numpy as np
import scipy.io.wavfile as wavfile

SETS = ["jade", "mech"]                                  # menu order
SYNTH_TYPES = ["Click", "Burst", "Zap", "Metal", "Chiff"]  # dsp/engines.lib
RATE = 44100

clips, names = [], []
for set_name in SETS:
    folder = f"tables/transients/{set_name}"
    manifest = json.load(open(f"{folder}/{set_name}.json"))
    assert manifest["sample_rate"] == RATE, f"{set_name}: expected {RATE} Hz"
    for n, entry in enumerate(manifest["samples"], 1):
        _, clip = wavfile.read(f"{folder}/{entry['file']}")
        clips.append(np.asarray(clip, dtype="<f4"))
        names.append(f"{set_name.capitalize()} {n:02d}")

starts = np.cumsum([0] + [len(c) for c in clips[:-1]])
np.concatenate(clips).tofile("plugin/src/translib.bin")

with open("plugin/src/translib_index.rs", "w") as f:
    f.write("// GENERATED by tools/gen-translib.py - do not edit.\n")
    f.write(f"pub const RATE: f32 = {RATE}.0;\n")
    f.write(f"pub const STARTS: [u32; {len(clips)}] = {list(map(int, starts))};\n")
    f.write(f"pub const LENS: [u32; {len(clips)}] = {[len(c) for c in clips]};\n")

menu = ";".join(f"'{n}':{i}" for i, n in enumerate(SYNTH_TYPES + names))
last = len(SYNTH_TYPES) + len(names) - 1
with open("dsp/translib.lib", "w") as f:
    f.write(f"""// GENERATED by tools/gen-translib.py - do not edit.
// {len(names)} samples ({", ".join(SETS)}) after {len(SYNTH_TYPES)} synthesized types.

synthTypes  = {len(SYNTH_TYPES)};
sampleRate  = {RATE};

// Sample k at position pos (in samples, interpolated; silent outside it),
// served by the plugin (plugin/src/translib.rs).
read(k, pos) = ffunction(float tr_read(int, float), "", "")(int(k), pos);

typeMenu(group) = group(nentry("[1]Type [style:menu{{{menu}}}]", 0, 0, {last}, 1));
""")
print(f"{len(names)} samples, {sum(map(len, clips))} frames; menu has {last + 1} types")
